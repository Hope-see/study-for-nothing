let currentTopic=null,currentQuestion=0,currentScore=0,answered=false;

function openPSLEMathLesson(topic){const lesson=psleMathLessons[topic];if(!lesson)return;currentTopic=topic;currentQuestion=0;currentScore=0;answered=false;document.getElementById("psle-math-dashboard").hidden=true;document.getElementById("psle-math-lesson").hidden=false;document.getElementById("psle-math-learn-stage").hidden=false;document.getElementById("psle-math-quiz-stage").hidden=true;document.getElementById("psle-math-finish-stage").hidden=true;document.getElementById("psle-math-lesson-icon").textContent=lesson.icon;document.getElementById("psle-math-lesson-label").textContent=lesson.label;document.getElementById("psle-math-lesson-title").textContent=lesson.title;document.getElementById("psle-math-lesson-description").textContent=lesson.description;document.getElementById("psle-math-example-icon").textContent=lesson.example.icon;document.getElementById("psle-math-example-title").textContent=lesson.example.title;document.getElementById("psle-math-example-text").textContent=lesson.example.text;const grid=document.getElementById("psle-math-fact-grid");grid.innerHTML="";lesson.facts.forEach(f=>{const b=document.createElement("button");b.className="fact-card";b.type="button";b.innerHTML=`<span class="fact-icon">${f.icon}</span><span class="fact-title">${f.title}</span><span class="fact-text">${f.text}</span><span class="fact-listen">🔊 Tap to hear</span>`;b.onclick=()=>speakPSLEMath(`${f.title}. ${f.text}`);grid.appendChild(b)});window.scrollTo({top:0,behavior:"smooth"})}
function closePSLEMathLesson(){stopPSLEMathSpeech();document.getElementById("psle-math-lesson").hidden=true;document.getElementById("psle-math-dashboard").hidden=false;updatePSLEMathProgress();window.scrollTo({top:0,behavior:"smooth"})}
function startPSLEMathQuiz(){currentQuestion=0;currentScore=0;answered=false;document.getElementById("psle-math-learn-stage").hidden=true;document.getElementById("psle-math-finish-stage").hidden=true;document.getElementById("psle-math-quiz-stage").hidden=false;showPSLEMathQuestion()}
function showPSLEMathQuestion(){const lesson=psleMathLessons[currentTopic],q=lesson.questions[currentQuestion],total=lesson.questions.length;answered=false;document.getElementById("psle-math-question-number").textContent=currentQuestion+1;document.getElementById("psle-math-question-total").textContent=total;document.getElementById("psle-math-question-text").textContent=q.text;document.getElementById("psle-math-question-visual").textContent=q.visual;document.getElementById("psle-math-live-score").textContent=currentScore;document.getElementById("psle-math-quiz-progress").style.width=`${((currentQuestion+1)/total)*100}%`;const f=document.getElementById("psle-math-feedback");f.textContent="";f.className="feedback";const g=document.getElementById("psle-math-answer-grid");g.innerHTML="";q.answers.forEach((a,i)=>{const b=document.createElement("button");b.className="answer-button";b.type="button";b.textContent=a;b.onclick=()=>checkPSLEMathAnswer(i,b);g.appendChild(b)})}
function checkPSLEMathAnswer(i,b){if(answered)return;answered=true;const lesson=psleMathLessons[currentTopic],q=lesson.questions[currentQuestion],buttons=[...document.querySelectorAll(".answer-button")],f=document.getElementById("psle-math-feedback");buttons.forEach(x=>x.disabled=true);buttons[q.correct].classList.add("correct");if(i===q.correct){currentScore++;b.classList.add("correct");f.textContent="✅ Correct! Great Math revision!";f.classList.add("good")}else{b.classList.add("wrong");f.textContent=`💡 Good try! The answer is ${q.answers[q.correct]}.`;f.classList.add("try-again")}document.getElementById("psle-math-live-score").textContent=currentScore;setTimeout(()=>{currentQuestion++;currentQuestion<lesson.questions.length?showPSLEMathQuestion():finishPSLEMathLesson()},1100)}
function finishPSLEMathLesson(){const lesson=psleMathLessons[currentTopic],total=lesson.questions.length;document.getElementById("psle-math-quiz-stage").hidden=true;document.getElementById("psle-math-finish-stage").hidden=false;document.getElementById("psle-math-final-score").textContent=`${currentScore} / ${total}`;let m="You finished the revision topic. Great effort!";if(currentScore===total)m="Perfect score! Excellent PSLE revision! 🌟";else if(currentScore>=3)m="Great job! Keep reviewing your weaker questions. 💪";else m="Good attempt! Review the reminder cards, then try again. 🧠";document.getElementById("psle-math-finish-message").textContent=m;savePSLEMathCompletion(currentTopic);updatePSLEMathProgress()}
function restartPSLEMathLesson(){startPSLEMathQuiz();window.scrollTo({top:0,behavior:"smooth"})}
function getPSLEMathCompletion(){try{return JSON.parse(localStorage.getItem("psleMathCompleted"))||{}}catch(e){return{}}}
function savePSLEMathCompletion(t){const c=getPSLEMathCompletion();c[t]=true;localStorage.setItem("psleMathCompleted",JSON.stringify(c))}
function updatePSLEMathProgress(){const c=getPSLEMathCompletion(),topics=Object.keys(psleMathLessons),done=topics.filter(t=>c[t]).length,pct=Math.round(done/topics.length*100);document.getElementById("psle-math-progress-text").textContent=`${pct}%`;document.getElementById("psle-math-progress-fill").style.width=`${pct}%`;document.getElementById("psle-math-progress-message").textContent=pct===100?"Amazing! You completed every PSLE Math revision topic! 🏆":pct>0?`${done} of ${topics.length} revision topics completed. Keep going!`:"Complete a revision topic to begin your PSLE Math challenge!";topics.forEach(t=>{const el=document.querySelector(`.psle-math-card[data-topic="${t}"]`),s=document.getElementById(`status-${t}`);if(el)el.classList.toggle("completed",Boolean(c[t]));if(s)s.textContent=c[t]?"Completed ✓":"Ready"})}
function speakPSLEMath(text){if(!("speechSynthesis" in window))return;speechSynthesis.cancel();const u=new SpeechSynthesisUtterance(text);u.rate=.82;u.pitch=1.02;speechSynthesis.speak(u)}
function stopPSLEMathSpeech(){if("speechSynthesis" in window)speechSynthesis.cancel()}
document.addEventListener("DOMContentLoaded",updatePSLEMathProgress);
