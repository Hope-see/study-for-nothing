let currentTopic=null,currentQuestion=0,currentScore=0,answered=false;

function openPSLEScienceLesson(topic){const lesson=psleScienceLessons[topic];if(!lesson)return;currentTopic=topic;currentQuestion=0;currentScore=0;answered=false;document.getElementById("psle-science-dashboard").hidden=true;document.getElementById("psle-science-lesson").hidden=false;document.getElementById("psle-science-learn-stage").hidden=false;document.getElementById("psle-science-quiz-stage").hidden=true;document.getElementById("psle-science-finish-stage").hidden=true;document.getElementById("psle-science-lesson-icon").textContent=lesson.icon;document.getElementById("psle-science-lesson-label").textContent=lesson.label;document.getElementById("psle-science-lesson-title").textContent=lesson.title;document.getElementById("psle-science-lesson-description").textContent=lesson.description;document.getElementById("psle-science-example-icon").textContent=lesson.example.icon;document.getElementById("psle-science-example-title").textContent=lesson.example.title;document.getElementById("psle-science-example-text").textContent=lesson.example.text;const grid=document.getElementById("psle-science-fact-grid");grid.innerHTML="";lesson.facts.forEach(f=>{const b=document.createElement("button");b.className="fact-card";b.type="button";b.innerHTML=`<span class="fact-icon">${f.icon}</span><span class="fact-title">${f.title}</span><span class="fact-text">${f.text}</span><span class="fact-listen">🔊 Tap to hear</span>`;b.onclick=()=>speakPSLEScience(`${f.title}. ${f.text}`);grid.appendChild(b)});window.scrollTo({top:0,behavior:"smooth"})}
function closePSLEScienceLesson(){stopPSLEScienceSpeech();document.getElementById("psle-science-lesson").hidden=true;document.getElementById("psle-science-dashboard").hidden=false;updatePSLEScienceProgress();window.scrollTo({top:0,behavior:"smooth"})}
function startPSLEScienceQuiz(){currentQuestion=0;currentScore=0;answered=false;document.getElementById("psle-science-learn-stage").hidden=true;document.getElementById("psle-science-finish-stage").hidden=true;document.getElementById("psle-science-quiz-stage").hidden=false;showPSLEScienceQuestion()}
function showPSLEScienceQuestion(){const lesson=psleScienceLessons[currentTopic],q=lesson.questions[currentQuestion],total=lesson.questions.length;answered=false;document.getElementById("psle-science-question-number").textContent=currentQuestion+1;document.getElementById("psle-science-question-total").textContent=total;document.getElementById("psle-science-question-text").textContent=q.text;document.getElementById("psle-science-question-visual").textContent=q.visual;document.getElementById("psle-science-live-score").textContent=currentScore;document.getElementById("psle-science-quiz-progress").style.width=`${((currentQuestion+1)/total)*100}%`;const f=document.getElementById("psle-science-feedback");f.textContent="";f.className="feedback";const g=document.getElementById("psle-science-answer-grid");g.innerHTML="";q.answers.forEach((a,i)=>{const b=document.createElement("button");b.className="answer-button";b.type="button";b.textContent=a;b.onclick=()=>checkPSLEScienceAnswer(i,b);g.appendChild(b)})}
function checkPSLEScienceAnswer(i,b){if(answered)return;answered=true;const lesson=psleScienceLessons[currentTopic],q=lesson.questions[currentQuestion],buttons=[...document.querySelectorAll(".answer-button")],f=document.getElementById("psle-science-feedback");buttons.forEach(x=>x.disabled=true);buttons[q.correct].classList.add("correct");if(i===q.correct){currentScore++;b.classList.add("correct");f.textContent="✅ Correct! Great Science revision!";f.classList.add("good")}else{b.classList.add("wrong");f.textContent=`💡 Good try! The answer is ${q.answers[q.correct]}.`;f.classList.add("try-again")}document.getElementById("psle-science-live-score").textContent=currentScore;setTimeout(()=>{currentQuestion++;currentQuestion<lesson.questions.length?showPSLEScienceQuestion():finishPSLEScienceLesson()},1100)}
function finishPSLEScienceLesson(){const lesson=psleScienceLessons[currentTopic],total=lesson.questions.length;document.getElementById("psle-science-quiz-stage").hidden=true;document.getElementById("psle-science-finish-stage").hidden=false;document.getElementById("psle-science-final-score").textContent=`${currentScore} / ${total}`;let m="You finished the revision topic. Great effort!";if(currentScore===total)m="Perfect score! Excellent PSLE revision! 🌟";else if(currentScore>=3)m="Great job! Keep reviewing your weaker questions. 💪";else m="Good attempt! Review the reminder cards, then try again. 🧠";document.getElementById("psle-science-finish-message").textContent=m;savePSLEScienceCompletion(currentTopic);updatePSLEScienceProgress()}
function restartPSLEScienceLesson(){startPSLEScienceQuiz();window.scrollTo({top:0,behavior:"smooth"})}
function getPSLEScienceCompletion(){try{return JSON.parse(localStorage.getItem("psleScienceCompleted"))||{}}catch(e){return{}}}
function savePSLEScienceCompletion(t){const c=getPSLEScienceCompletion();c[t]=true;localStorage.setItem("psleScienceCompleted",JSON.stringify(c))}
function updatePSLEScienceProgress(){const c=getPSLEScienceCompletion(),topics=Object.keys(psleScienceLessons),done=topics.filter(t=>c[t]).length,pct=Math.round(done/topics.length*100);document.getElementById("psle-science-progress-text").textContent=`${pct}%`;document.getElementById("psle-science-progress-fill").style.width=`${pct}%`;document.getElementById("psle-science-progress-message").textContent=pct===100?"Amazing! You completed every PSLE Science revision topic! 🏆":pct>0?`${done} of ${topics.length} revision topics completed. Keep going!`:"Complete a revision topic to begin your PSLE Science challenge!";topics.forEach(t=>{const el=document.querySelector(`.psle-science-card[data-topic="${t}"]`),s=document.getElementById(`status-${t}`);if(el)el.classList.toggle("completed",Boolean(c[t]));if(s)s.textContent=c[t]?"Completed ✓":"Ready"})}
function speakPSLEScience(text){if(!("speechSynthesis" in window))return;speechSynthesis.cancel();const u=new SpeechSynthesisUtterance(text);u.rate=.82;u.pitch=1.02;speechSynthesis.speak(u)}
function stopPSLEScienceSpeech(){if("speechSynthesis" in window)speechSynthesis.cancel()}
document.addEventListener("DOMContentLoaded",updatePSLEScienceProgress);
