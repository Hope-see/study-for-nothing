function closePSLEEnglishLesson(){stopPSLEEnglishSpeech();document.getElementById("psle-english-lesson").hidden=true;document.getElementById("psle-english-dashboard").hidden=false;updatePSLEEnglishProgress();window.scrollTo({top:0,behavior:"smooth"})}
function startPSLEEnglishQuiz(){currentQuestion=0;currentScore=0;answered=false;document.getElementById("psle-english-learn-stage").hidden=true;document.getElementById("psle-english-finish-stage").hidden=true;document.getElementById("psle-english-quiz-stage").hidden=false;showPSLEEnglishQuestion()}
function showPSLEEnglishQuestion(){const lesson=psleEnglishLessons[currentTopic],q=lesson.questions[currentQuestion],total=lesson.questions.length;answered=false;document.getElementById("psle-english-question-number").textContent=currentQuestion+1;document.getElementById("psle-english-question-total").textContent=total;document.getElementById("psle-english-question-text").textContent=q.text;document.getElementById("psle-english-question-visual").textContent=q.visual;document.getElementById("psle-english-live-score").textContent=currentScore;document.getElementById("psle-english-quiz-progress").style.width=`${((currentQuestion+1)/total)*100}%`;const f=document.getElementById("psle-english-feedback");f.textContent="";f.className="feedback";const g=document.getElementById("psle-english-answer-grid");g.innerHTML="";q.answers.forEach((a,i)=>{const b=document.createElement("button");b.className="answer-button";b.type="button";b.textContent=a;b.onclick=()=>checkPSLEEnglishAnswer(i,b);g.appendChild(b)})}
function checkPSLEEnglishAnswer(i,b){if(answered)return;answered=true;const lesson=psleEnglishLessons[currentTopic],q=lesson.questions[currentQuestion],buttons=[...document.querySelectorAll(".answer-button")],f=document.getElementById("psle-english-feedback");buttons.forEach(x=>x.disabled=true);buttons[q.correct].classList.add("correct");if(i===q.correct){currentScore++;b.classList.add("correct");f.textContent="✅ Correct! Great English revision!";f.classList.add("good")}else{b.classList.add("wrong");f.textContent=`💡 Good try! The answer is ${q.answers[q.correct]}.`;f.classList.add("try-again")}document.getElementById("psle-english-live-score").textContent=currentScore;setTimeout(()=>{currentQuestion++;currentQuestion<lesson.questions.length?showPSLEEnglishQuestion():finishPSLEEnglishLesson()},1100)}
function finishPSLEEnglishLesson(){const lesson=psleEnglishLessons[currentTopic],total=lesson.questions.length;document.getElementById("psle-english-quiz-stage").hidden=true;document.getElementById("psle-english-finish-stage").hidden=false;document.getElementById("psle-english-final-score").textContent=`${currentScore} / ${total}`;let m="You finished the revision topic. Great effort!";if(currentScore===total)m="Perfect score! Excellent PSLE revision! 🌟";else if(currentScore>=3)m="Great job! Keep reviewing your weaker questions. 💪";else m="Good attempt! Review the reminder cards, then try again. 🧠";document.getElementById("psle-english-finish-message").textContent=m;savePSLEEnglishCompletion(currentTopic);updatePSLEEnglishProgress()}
function restartPSLEEnglishLesson(){startPSLEEnglishQuiz();window.scrollTo({top:0,behavior:"smooth"})}
function getPSLEEnglishCompletion(){try{return JSON.parse(localStorage.getItem("psleEnglishCompleted"))||{}}catch(e){return{}}}
function savePSLEEnglishCompletion(t){const c=getPSLEEnglishCompletion();c[t]=true;localStorage.setItem("psleEnglishCompleted",JSON.stringify(c))}
function updatePSLEEnglishProgress(){const c=getPSLEEnglishCompletion(),topics=Object.keys(psleEnglishLessons),done=topics.filter(t=>c[t]).length,pct=Math.round(done/topics.length*100);document.getElementById("psle-english-progress-text").textContent=`${pct}%`;document.getElementById("psle-english-progress-fill").style.width=`${pct}%`;document.getElementById("psle-english-progress-message").textContent=pct===100?"Amazing! You completed every PSLE English revision topic! 🏆":pct>0?`${done} of ${topics.length} revision topics completed. Keep going!`:"Complete a revision topic to begin your PSLE English challenge!";topics.forEach(t=>{const el=document.querySelector(`.psle-english-card[data-topic="${t}"]`),s=document.getElementById(`status-${t}`);if(el)el.classList.toggle("completed",Boolean(c[t]));if(s)s.textContent=c[t]?"Completed ✓":"Ready"})}
function speakPSLEEnglish(text){if(!("speechSynthesis" in window))return;speechSynthesis.cancel();const u=new SpeechSynthesisUtterance(text);u.rate=.82;u.pitch=1.02;speechSynthesis.speak(u)}
function stopPSLEEnglishSpeech(){if("speechSynthesis" in window)speechSynthesis.cancel()}
